// assessment.js — AI questionnaire and summary via the `aiAssist` Cloud Function.
// The AI key lives on the server; everything the AI returns is sanitised before display.
(function () {
    'use strict';
    const { $, esc } = RV;
    const fb = RV.fb;
    const form = $('#config');
    const msg = form.querySelector('.form-msg');
    const KEY = 'rv-assessments';
    let current = null; // { id, created, patient, html, answers, report }

    form.questionCount.addEventListener('input', () => { $('#count-val').textContent = form.questionCount.value; });

    const callAI = async payload => {
        if (fb && !fb.functions && RV.loadSdk) await RV.loadSdk(['functions']);
        if (!fb || !fb.functions) throw new Error('The AI service is not available right now.');
        await RV.requireAuth('Create a free account or sign in to use the AI assessment.');
        const res = await fb.functions.httpsCallable('aiAssist', { timeout: 120000 })(payload);
        return (res.data && res.data.html) || '';
    };
    const aiError = err => {
        const code = String((err && err.code) || '').replace(/^functions\//, '');
        if (['resource-exhausted', 'unauthenticated', 'invalid-argument', 'permission-denied', 'failed-precondition'].includes(code)) return err.message;
        if (/cancelled/i.test((err && err.message) || '')) return 'Please sign in to continue.';
        return 'The AI service is busy or unreachable. Please try again in a minute.';
    };
    const loading = (on, text) => { $('#loading').hidden = !on; if (text) $('#loading-text').textContent = text; };

    function paperHead(p) {
        return `<div class="paper-head"><h2 class="mb-0">${esc(p.category)} questionnaire</h2>
            <p class="mb-0">${esc(p.name || 'Client')}${p.age ? ` · ${esc(p.age)} years` : ''}${p.gender ? ` · ${esc(p.gender)}` : ''} · ${esc(p.condition)}</p>
            <small>Examiner: ${esc(p.examiner)} · ${esc(RV.date(Date.now()))} · RehabVerve</small></div>`;
    }

    function show(a) {
        current = a;
        $('#paper').innerHTML = paperHead(a.patient) + RV.sanitize(a.html, 'form');
        restoreAnswers(a.answers || {});
        const r = $('#report');
        r.hidden = !a.report;
        r.innerHTML = a.report ? `<div class="paper-head"><h2 class="mb-0">Summary and suggested specialists</h2><small>Generated by AI to support — not replace — a professional assessment.</small></div>${RV.sanitize(a.report, 'report')}` : '';
        $('#output').hidden = false;
        form.hidden = true;
    }

    form.addEventListener('submit', async e => {
        e.preventDefault();
        msg.hidden = true;
        const v = RV.formValues(form);
        if (!v.condition) { msg.textContent = 'Please describe the main concern.'; msg.hidden = false; return; }
        const btn = $('#generate');
        RV.busy(btn, true, 'Generating…');
        loading(true, 'Creating your questionnaire — this can take up to a minute…');
        try {
            const html = await callAI({ task: 'questionnaire', ...v });
            if (!html) throw new Error('empty');
            show({ id: 'a' + Date.now(), created: Date.now(), patient: v, html, answers: {}, report: '' });
            persist();
            $('#output').scrollIntoView({ behavior: 'smooth' });
        } catch (err) {
            msg.textContent = aiError(err);
            msg.hidden = false;
        } finally {
            RV.busy(btn, false);
            loading(false);
        }
    });

    // ---------- answers ----------
    function readAnswers() {
        const out = {};
        $('#paper').querySelectorAll('input, textarea').forEach(el => {
            if (!el.name) return;
            if (el.type === 'radio') { if (el.checked) out[el.name] = el.value; }
            else if (el.type === 'checkbox') { out[el.name] = out[el.name] || []; if (el.checked) out[el.name].push(el.value); }
            else if (el.value.trim()) out[el.name] = el.value.trim();
        });
        return out;
    }
    function restoreAnswers(ans) {
        $('#paper').querySelectorAll('input, textarea').forEach(el => {
            const v = ans[el.name];
            if (v == null) return;
            if (el.type === 'radio') el.checked = el.value === v;
            else if (el.type === 'checkbox') el.checked = Array.isArray(v) && v.includes(el.value);
            else el.value = v;
        });
    }
    function answersText() {
        return Array.from($('#paper').querySelectorAll('.q')).map((q, i) => {
            const text = (q.querySelector('.q-text') || q).textContent.trim().replace(/\s+/g, ' ').slice(0, 300);
            const picked = Array.from(q.querySelectorAll('input:checked')).map(x => (x.closest('label') || x).textContent.trim() || x.value);
            const typed = Array.from(q.querySelectorAll('textarea, input[type=text], input[type=number]')).map(x => x.value.trim()).filter(Boolean);
            const answer = picked.concat(typed).join('; ');
            return answer ? `${i + 1}. ${text}\n   Answer: ${answer}` : '';
        }).filter(Boolean).join('\n');
    }
    $('#paper').addEventListener('change', RV.debounce(() => { if (current) { current.answers = readAnswers(); persist(); } }, 300));

    $('#evaluate').addEventListener('click', async e => {
        const answers = answersText();
        if (!answers) { RV.toast('Please answer some questions first.', 'error'); return; }
        const btn = e.currentTarget;
        RV.busy(btn, true, 'Summarising…');
        loading(true, 'Summarising the answers…');
        try {
            const html = await callAI({ task: 'report', ...current.patient, answers });
            current.report = html;
            current.answers = readAnswers();
            persist();
            show(current);
            $('#report').scrollIntoView({ behavior: 'smooth' });
        } catch (err) {
            RV.toast(aiError(err), 'error', 6000);
        } finally {
            RV.busy(btn, false);
            loading(false);
        }
    });

    // ---------- saved on device ----------
    const saved = () => RV.store.get(KEY, []) || [];
    function persist() {
        if (!current) return;
        const list = saved().filter(a => a.id !== current.id);
        list.unshift(current);
        RV.store.set(KEY, list.slice(0, 20));
        renderSaved();
    }
    function renderSaved() {
        const list = saved();
        $('#saved').innerHTML = list.length ? list.map(a => `
            <div class="card list-item" data-id="${esc(a.id)}">
                <div><h4>${esc(a.patient.name || 'Client')} · ${esc(a.patient.category)}</h4><p>${esc(a.patient.condition)} · ${esc(RV.date(a.created))}</p></div>
                <div class="row"><button class="btn btn-sm" data-open>Open</button><button class="btn btn-sm btn-ghost btn-icon" data-del aria-label="Delete"><i class='bx bx-trash'></i></button></div>
            </div>`).join('') : '<p class="muted mb-0">Your saved assessments appear here. They stay on this device only.</p>';
    }
    $('#saved').addEventListener('click', e => {
        const row = e.target.closest('[data-id]');
        if (!row) return;
        const a = saved().find(x => x.id === row.dataset.id);
        if (e.target.closest('[data-open]') && a) { show(a); $('#output').scrollIntoView({ behavior: 'smooth' }); }
        if (e.target.closest('[data-del]')) { RV.store.set(KEY, saved().filter(x => x.id !== row.dataset.id)); renderSaved(); }
    });

    $('#save').addEventListener('click', () => { current.answers = readAnswers(); persist(); RV.toast('Saved on this device', 'success'); });
    $('#print').addEventListener('click', () => window.print());
    $('#new').addEventListener('click', () => { current = null; $('#output').hidden = true; form.hidden = false; form.scrollIntoView({ behavior: 'smooth' }); });

    renderSaved();
})();
